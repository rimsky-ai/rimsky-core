func TestSpliceIdempotency(t *testing.T) {
	dir := t.TempDir()
	cases := []struct {
		name   string
		body   string
		header string
		kind   sourceKind
	}{
		{"go", "package foo\n", apacheHeaderGo, kindGo},
		{"ts", "import x from 'y';\n", apacheHeaderTS, kindTS},
		{"proto", "syntax = \"proto3\";\n", apacheHeaderProto, kindProto},
		{"sql", "CREATE TABLE x();\n", apacheHeaderSQL, kindSQL},
		{"shell", "#!/bin/bash\necho\n", apacheHeaderShell, kindShell},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			path := dir + "/" + tc.name
			out := splice([]byte(tc.body), tc.header, tc.kind)
			if err := writeTestFile(path, out); err != nil {
				t.Fatalf("write: %v", err)
			}
			has, _, _, err := detectHeader(path)
			if err != nil {
				t.Fatalf("detect: %v", err)
			}
			if !has {
				t.Errorf("after splice, detectHeader should report hasHeader=true; first 200 bytes: %q", string(out)[:min(200, len(out))])
			}
		})
	}
}

func TestDetectHeaderApacheVsAGPL(t *testing.T) {
	dir := t.TempDir()
	apa := dir + "/a.go"
	if err := writeTestFile(apa, []byte(apacheHeaderGo+"\npackage x\n")); err != nil {
		t.Fatal(err)
	}
	agp := dir + "/g.go"
	if err := writeTestFile(agp, []byte(agplHeaderGo+"\npackage x\n")); err != nil {
		t.Fatal(err)
	}
	{
		has, isApa, isAgp, err := detectHeader(apa)
		if err != nil {
			t.Fatal(err)
		}
		if !has || !isApa || isAgp {
			t.Errorf("apache header detected wrong: has=%v apa=%v agp=%v", has, isApa, isAgp)
		}
	}
	{
		has, isApa, isAgp, err := detectHeader(agp)
		if err != nil {
			t.Fatal(err)
		}
		if !has || isApa || !isAgp {
			t.Errorf("agpl header detected wrong: has=%v apa=%v agp=%v", has, isApa, isAgp)
		}
	}
}

func TestStampReplacesWrongKindHeader(t *testing.T) {
	dir := t.TempDir()
	path := dir + "/x.go"
	orig := apacheHeaderGo + "\n// Package x does things.\npackage x\n\nfunc F() {}\n"
	if err := writeTestFile(path, []byte(orig)); err != nil {
		t.Fatal(err)
	}
	f := fileEntry{relPath: "x.go", absPath: path, kind: kindGo, classification: classAGPL}
	if err := stampOne(f, true); err != nil {
		t.Fatalf("stampOne: %v", err)
	}
	s := readFileString(t, path)
	if !strings.HasPrefix(s, agplHeaderGo) {
		t.Errorf("expected AGPL header at top, got:\n%s", s[:min(160, len(s))])
	}
	if strings.Contains(s, "Licensed under the Apache License") {
		t.Errorf("old Apache header should be gone:\n%s", s)
	}
	for _, want := range []string{"// Package x does things.", "package x", "func F() {}"} {
		if !strings.Contains(s, want) {
			t.Errorf("body must be preserved; missing %q:\n%s", want, s)
		}
	}
	if strings.Count(s, "Copyright © 2026") != 1 {
		t.Errorf("exactly one copyright line expected:\n%s", s)
	}
}

