func TestSpliceGoBeforePackage(t *testing.T) {
	body := []byte("package foo\n\nfunc Bar() {}\n")
	out := splice(body, apacheHeaderGo, kindGo)
	if !strings.HasPrefix(string(out), apacheHeaderGo) {
		t.Errorf("header should be at top, got: %q", string(out)[:60])
	}
	if !strings.Contains(string(out), "package foo") {
		t.Errorf("package decl missing")
	}
}

func TestSpliceGoPackageDocImmediatelyBeforePackage(t *testing.T) {
	body := []byte("// Package foo does X.\npackage foo\n")
	out := splice(body, apacheHeaderGo, kindGo)
	lines := strings.Split(string(out), "\n")
	pkgIdx := -1
	for i, ln := range lines {
		if strings.HasPrefix(ln, "package ") {
			pkgIdx = i
			break
		}
	}
	if pkgIdx <= 0 {
		t.Fatalf("package decl not found")
	}
	if !strings.HasPrefix(lines[pkgIdx-1], "// Package foo") {
		t.Errorf("package-doc comment should be immediately above package, got %q", lines[pkgIdx-1])
	}
}

